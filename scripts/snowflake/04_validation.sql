-- Quality and reconciliation checks. These are review queries, not gates that
-- mutate source data. Every expected dataset invariant returns explicit PASS
-- or FAIL. COUNT_IF is wrapped because Snowflake returns NULL for zero matches.

SELECT 'row_count' AS CHECK_NAME, COUNT(*) AS ACTUAL, 2000 AS EXPECTED,
       IFF(COUNT(*) = 2000, 'PASS', 'FAIL') AS STATUS
FROM SIGNALGRID_REPORT_OBSERVATIONS;

SELECT 'unique_reports' AS CHECK_NAME, COUNT(DISTINCT REPORT_ID) AS ACTUAL, 100 AS EXPECTED,
       IFF(COUNT(DISTINCT REPORT_ID) = 100, 'PASS', 'FAIL') AS STATUS
FROM SIGNALGRID_REPORT_OBSERVATIONS;

WITH per_report AS (
  SELECT REPORT_ID, COUNT(*) AS OBSERVATIONS
  FROM SIGNALGRID_REPORT_OBSERVATIONS
  GROUP BY REPORT_ID
)
SELECT 'observations_per_report' AS CHECK_NAME,
       MIN(OBSERVATIONS) AS ACTUAL_MIN, MAX(OBSERVATIONS) AS ACTUAL_MAX,
       20 AS EXPECTED,
       IFF(COUNT(*) = 100 AND MIN(OBSERVATIONS) = 20 AND MAX(OBSERVATIONS) = 20, 'PASS', 'FAIL') AS STATUS
FROM per_report;

SELECT 'orphan_owner_rows' AS CHECK_NAME,
       COALESCE(COUNT_IF(LOWER(TRIM(COALESCE(OWNER_EMAIL, ''))) IN ('', 'nan', 'null', 'n/a', 'orphaned_report')), 0) AS ACTUAL,
       245 AS EXPECTED,
       IFF(COALESCE(COUNT_IF(LOWER(TRIM(COALESCE(OWNER_EMAIL, ''))) IN ('', 'nan', 'null', 'n/a', 'orphaned_report')), 0) = 245, 'PASS', 'FAIL') AS STATUS
FROM SIGNALGRID_REPORT_OBSERVATIONS;

SELECT 'negative_credit_rows' AS CHECK_NAME, COALESCE(COUNT_IF(SNOWFLAKE_CREDITS_CONSUMED < 0), 0) AS ACTUAL,
       24 AS EXPECTED, IFF(COALESCE(COUNT_IF(SNOWFLAKE_CREDITS_CONSUMED < 0), 0) = 24, 'PASS', 'FAIL') AS STATUS
FROM SIGNALGRID_REPORT_OBSERVATIONS;

SELECT 'latency_over_15_seconds' AS CHECK_NAME, COALESCE(COUNT_IF(AVG_LOAD_TIME_SEC > 15), 0) AS ACTUAL,
       1490 AS EXPECTED, IFF(COALESCE(COUNT_IF(AVG_LOAD_TIME_SEC > 15), 0) = 1490, 'PASS', 'FAIL') AS STATUS
FROM SIGNALGRID_REPORT_OBSERVATIONS;

SELECT 'zero_active_view_rows' AS CHECK_NAME, COALESCE(COUNT_IF(MONTHLY_ACTIVE_VIEWS = 0), 0) AS ACTUAL,
       4 AS EXPECTED, IFF(COALESCE(COUNT_IF(MONTHLY_ACTIVE_VIEWS = 0), 0) = 4, 'PASS', 'FAIL') AS STATUS
FROM SIGNALGRID_REPORT_OBSERVATIONS;

WITH expected AS (
  SELECT COLUMN1 AS LAST_REFRESH_STATUS, COLUMN2 AS EXPECTED
  FROM VALUES ('SUCCESS', 1336), ('FAILED', 382), ('TIMED_OUT', 182), ('UNKNOWN', 100)
), actual AS (
  SELECT LAST_REFRESH_STATUS, COUNT(*) AS ACTUAL
  FROM SIGNALGRID_REPORT_OBSERVATIONS
  GROUP BY LAST_REFRESH_STATUS
)
SELECT 'refresh_state_' || e.LAST_REFRESH_STATUS AS CHECK_NAME,
       COALESCE(a.ACTUAL, 0) AS ACTUAL, e.EXPECTED,
       IFF(COALESCE(a.ACTUAL, 0) = e.EXPECTED, 'PASS', 'FAIL') AS STATUS
FROM expected e LEFT JOIN actual a USING (LAST_REFRESH_STATUS)
ORDER BY e.LAST_REFRESH_STATUS;

SELECT 'zero_view_cost_ratio_null_safe' AS CHECK_NAME,
       COALESCE(COUNT_IF(MONTHLY_ACTIVE_VIEWS = 0 AND CREDITS_PER_ACTIVE_VIEW IS NOT NULL), 0) AS ACTUAL,
       0 AS EXPECTED,
       IFF(COALESCE(COUNT_IF(MONTHLY_ACTIVE_VIEWS = 0 AND CREDITS_PER_ACTIVE_VIEW IS NOT NULL), 0) = 0, 'PASS', 'FAIL') AS STATUS
FROM SIGNALGRID_OBSERVATION_COSTS;

SELECT 'invalid_credit_exclusion' AS CHECK_NAME,
       COALESCE(COUNT_IF(ATTRIBUTION_STATUS = 'EXCLUDED_NEGATIVE_CREDITS' AND VALID_CREDITS IS NOT NULL), 0) AS ACTUAL,
       0 AS EXPECTED,
       IFF(COALESCE(COUNT_IF(ATTRIBUTION_STATUS = 'EXCLUDED_NEGATIVE_CREDITS' AND VALID_CREDITS IS NOT NULL), 0) = 0, 'PASS', 'FAIL') AS STATUS
FROM SIGNALGRID_OBSERVATION_COSTS;
