-- SignalGrid Snowflake-compatible review schema.
-- The supplied CSV is an observation extract, not a native ACCOUNT_USAGE export.
CREATE OR REPLACE TABLE SIGNALGRID_REPORT_OBSERVATIONS (
  SOURCE_OBSERVATION_ID VARCHAR NOT NULL,
  REPORT_ID VARCHAR NOT NULL,
  REPORT_NAME VARCHAR NOT NULL,
  OWNER_EMAIL VARCHAR,
  LAST_REFRESH_STATUS VARCHAR,
  MONTHLY_ACTIVE_VIEWS NUMBER,
  SNOWFLAKE_CREDITS_CONSUMED FLOAT,
  AVG_LOAD_TIME_SEC FLOAT,
  AWS_HOSTING_COST_USD FLOAT,
  QUERY_COUNT_LAST_30D NUMBER,
  CONCURRENT_USER_PEAK NUMBER,
  SOURCE_ROW_NUMBER NUMBER,
  SOURCE_FILE_NAME VARCHAR,
  SOURCE_FILE_CONTENT_KEY VARCHAR,
  SOURCE_FILE_SHA256 VARCHAR,
  INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Optional, explicitly simulated ACCOUNT_USAGE-compatible attribution input.
-- Do not populate this table from invented values in production.
CREATE OR REPLACE TABLE SIGNALGRID_SIMULATED_QUERY_HISTORY (
  QUERY_ID VARCHAR NOT NULL,
  QUERY_START_TIME TIMESTAMP_NTZ,
  WAREHOUSE_NAME VARCHAR,
  REPORT_ID VARCHAR,
  CREDITS_USED_CLOUD_SERVICES FLOAT,
  CREDITS_USED_COMPUTE FLOAT,
  ACTIVE_VIEW_COUNT NUMBER,
  SOURCE_LABEL VARCHAR DEFAULT 'SIMULATED_ACCOUNT_USAGE'
);

CREATE OR REPLACE TABLE SIGNALGRID_CREDIT_RATE (
  RATE_NAME VARCHAR PRIMARY KEY,
  USD_PER_CREDIT NUMBER(18,6),
  ASSUMPTION_NOTE VARCHAR
);
