-- Observation-level attribution supported by the supplied CSV.
-- Negative credits are invalid and excluded. Zero views return NULL, not infinity.
CREATE OR REPLACE VIEW SIGNALGRID_OBSERVATION_COSTS AS
SELECT
  SOURCE_OBSERVATION_ID, REPORT_ID, REPORT_NAME, OWNER_EMAIL,
  MONTHLY_ACTIVE_VIEWS, SNOWFLAKE_CREDITS_CONSUMED, AWS_HOSTING_COST_USD,
  IFF(SNOWFLAKE_CREDITS_CONSUMED >= 0, SNOWFLAKE_CREDITS_CONSUMED, NULL) AS VALID_CREDITS,
  IFF(SNOWFLAKE_CREDITS_CONSUMED >= 0 AND MONTHLY_ACTIVE_VIEWS > 0,
      SNOWFLAKE_CREDITS_CONSUMED / MONTHLY_ACTIVE_VIEWS, NULL) AS CREDITS_PER_ACTIVE_VIEW,
  IFF(MONTHLY_ACTIVE_VIEWS > 0,
      AWS_HOSTING_COST_USD / MONTHLY_ACTIVE_VIEWS, NULL) AS AWS_COST_PER_ACTIVE_VIEW_USD,
  IFF(SNOWFLAKE_CREDITS_CONSUMED < 0, 'EXCLUDED_NEGATIVE_CREDITS',
      IFF(MONTHLY_ACTIVE_VIEWS = 0, 'UNDEFINED_ZERO_VIEWS', 'VALID')) AS ATTRIBUTION_STATUS
FROM SIGNALGRID_REPORT_OBSERVATIONS;

-- Report-level view. MEDIAN is intentional: 20 repeated rows per report have
-- no timestamp and cannot be treated as a chronological monthly history or summed.
CREATE OR REPLACE VIEW SIGNALGRID_REPORT_COST_SUMMARY AS
SELECT
  REPORT_ID, ANY_VALUE(REPORT_NAME) AS REPORT_NAME,
  COUNT(*) AS OBSERVATION_COUNT,
  MEDIAN(IFF(VALID_CREDITS IS NOT NULL, VALID_CREDITS, NULL)) AS MEDIAN_CREDITS,
  MEDIAN(MONTHLY_ACTIVE_VIEWS) AS MEDIAN_ACTIVE_VIEWS,
  MEDIAN(CREDITS_PER_ACTIVE_VIEW) AS MEDIAN_CREDITS_PER_ACTIVE_VIEW,
  MEDIAN(AWS_HOSTING_COST_USD) AS MEDIAN_AWS_HOSTING_COST_USD,
  MEDIAN(AWS_COST_PER_ACTIVE_VIEW_USD) AS MEDIAN_AWS_COST_PER_ACTIVE_VIEW_USD,
  COALESCE(COUNT_IF(ATTRIBUTION_STATUS = 'EXCLUDED_NEGATIVE_CREDITS'), 0) AS INVALID_CREDIT_ROWS,
  COALESCE(COUNT_IF(ATTRIBUTION_STATUS = 'UNDEFINED_ZERO_VIEWS'), 0) AS ZERO_VIEW_ROWS
FROM SIGNALGRID_OBSERVATION_COSTS
GROUP BY REPORT_ID;

-- Explicitly simulated ACCOUNT_USAGE-style path. Attribution uses a supplied
-- REPORT_ID label; if query logs lack that label, no defensible attribution exists.
CREATE OR REPLACE VIEW SIGNALGRID_SIMULATED_ACCOUNT_USAGE_ATTRIBUTION AS
SELECT
  REPORT_ID,
  SUM(IFF(CREDITS_USED_COMPUTE >= 0, CREDITS_USED_COMPUTE, 0)) AS COMPUTE_CREDITS,
  SUM(IFF(CREDITS_USED_CLOUD_SERVICES >= 0, CREDITS_USED_CLOUD_SERVICES, 0)) AS CLOUD_SERVICES_CREDITS,
  SUM(IFF(CREDITS_USED_COMPUTE >= 0, CREDITS_USED_COMPUTE, 0) + IFF(CREDITS_USED_CLOUD_SERVICES >= 0, CREDITS_USED_CLOUD_SERVICES, 0)) AS TOTAL_CREDITS,
  SUM(IFF(CREDITS_USED_COMPUTE >= 0 OR CREDITS_USED_CLOUD_SERVICES >= 0, ACTIVE_VIEW_COUNT, 0)) AS ATTRIBUTED_ACTIVE_VIEWS,
  IFF(SUM(IFF(CREDITS_USED_COMPUTE >= 0 OR CREDITS_USED_CLOUD_SERVICES >= 0, ACTIVE_VIEW_COUNT, 0)) > 0,
      SUM(IFF(CREDITS_USED_COMPUTE >= 0, CREDITS_USED_COMPUTE, 0) + IFF(CREDITS_USED_CLOUD_SERVICES >= 0, CREDITS_USED_CLOUD_SERVICES, 0)) /
      SUM(IFF(CREDITS_USED_COMPUTE >= 0 OR CREDITS_USED_CLOUD_SERVICES >= 0, ACTIVE_VIEW_COUNT, 0)), NULL) AS CREDITS_PER_ACTIVE_VIEW
FROM SIGNALGRID_SIMULATED_QUERY_HISTORY
WHERE REPORT_ID IS NOT NULL
GROUP BY REPORT_ID;
